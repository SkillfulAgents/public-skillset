def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--answers", help="JSON file of interview answers (partial config)")
    ap.add_argument("--force", action="store_true",
                    help="overwrite an existing config/outbound.yaml")
    ap.add_argument("--skip-claude-md", action="store_true")
    ap.add_argument("--regen-claude-md", action="store_true",
                    help="rewrite CLAUDE.md from the existing config and exit; "
                         "touches no config, no database, no positioning files")
    ap.add_argument("--demo", action="store_true",
                    help="load the worked Northwind Logistics example so the whole "
                         "motion can be run before any interview happens")
    args = ap.parse_args()

    if args.demo:
        if TARGET.exists() and not args.force:
            print(f"{TARGET.relative_to(ROOT)} already exists; --demo would overwrite "
                  f"it. Re-run with --force if that is what you want.", file=sys.stderr)
            return 1
        for src_rel, dst_rel in DEMO_FILES.items():
            dst = ROOT / dst_rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes((DEMO / src_rel).read_bytes())

        # The demo has to be reproducible: a leftover database makes the second
        # run suppress every prospect the first run stored, which reads as a
        # broken pipeline. Refuse rather than delete anything with real sends.
        db_path = ROOT / _get(yaml.safe_load(TARGET.read_text()),
                              "adapter_config.sqlite.path", "data/campaigns.db")
        if db_path.exists():
            n = sqlite3.connect(db_path).execute(
                "SELECT COUNT(*) FROM sqlite_master WHERE name='sends'").fetchone()[0]
            sends = (sqlite3.connect(db_path).execute(
                "SELECT COUNT(*) FROM sends").fetchone()[0] if n else 0)
            if sends:
                print(f"{db_path.relative_to(ROOT)} has {sends} logged send(s). "
                      f"Refusing to reset it. Move it aside first if you want a "
                      f"clean demo.", file=sys.stderr)
                return 1
            db_path.unlink()
        db.init(db_path)
        CLAUDE_MD.write_text(render_claude_md(yaml.safe_load(TARGET.read_text())))
        print("Loaded the Northwind Logistics demo. Sender is 'dryrun'.\n"
              "  uv run --with pyyaml .claude/skills/outbound-campaign/scripts/pipeline.py\n"
              "Run onboarding with --force when you want your own config.")
        return 0

    # CLAUDE.md is derived, so it goes stale every time the config is edited by
    # hand. Without this it could only be refreshed by re-running onboarding.
    if args.regen_claude_md:
        if not TARGET.exists():
            print(f"no {TARGET.relative_to(ROOT)} to render from; run onboarding first",
                  file=sys.stderr)
            return 1
        (ROOT / "CLAUDE.md").write_text(
            render_claude_md(yaml.safe_load(TARGET.read_text())))
        print(f"regenerated CLAUDE.md from {TARGET.relative_to(ROOT)}")
        return 0

    if TARGET.exists() and not args.force:
        print(f"refusing to overwrite existing {TARGET.relative_to(ROOT)} (use --force)",
              file=sys.stderr)
        return 1

    base = yaml.safe_load(EXAMPLE.read_text())
    answers = {}
    if args.answers:
        p = pathlib.Path(args.answers)
        if not p.exists():
            print(f"answers file not found: {p}", file=sys.stderr)
            return 2
        answers = json.loads(p.read_text())
        if not isinstance(answers, dict):
            print("answers must be a JSON object", file=sys.stderr)
            return 2

    cfg = deep_merge(base, answers)
    company = _get(cfg, "company.name", "your company")

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(
        HEADER.format(company=company)
        + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=88)
    )
    written = [TARGET]

    for rel in ("data", "data/dry-runs", "positioning", "docs"):
        (ROOT / rel).mkdir(parents=True, exist_ok=True)

    db_path = _get(cfg, "adapter_config.sqlite.path", "data/campaigns.db")
    conn = db.init(ROOT / db_path)
    conn.close()
    written.append(ROOT / db_path)

    pos_md = ROOT / str(_get(cfg, "positioning.positioning_file",
                             "positioning/positioning.md"))
    if not pos_md.exists():
        pos_md.parent.mkdir(parents=True, exist_ok=True)
        pos_md.write_text(POSITIONING_MD.format(
            company=company,
            wedge=_get(cfg, "positioning.wedge", "(TODO)"),
            pain=_get(cfg, "positioning.pain", "(TODO)"),
            not_a=", ".join(str(x) for x in (_get(cfg, "positioning.not_a", []) or []))
                  or "(TODO)",
            proof=_get(cfg, "positioning.proof_metric", "(TODO)"),
        ))
        written.append(pos_md)

    uc = ROOT / str(_get(cfg, "positioning.use_cases_file", "positioning/use-cases.json"))
    if not uc.exists():
        uc.parent.mkdir(parents=True, exist_ok=True)
        uc.write_text(json.dumps(USE_CASES_STUB, indent=2) + "\n")
        written.append(uc)

    for rel, content in (("data/seen.json", "[]\n"),
                         ("data/blocklist_domains.json", "[]\n")):
        p = ROOT / rel
        if not p.exists():
            p.write_text(content)
            written.append(p)

    # Voice samples are the highest-leverage thing the operator provides and the
    # easiest to skip, so seed the file with the shipped example to fill in.
    notes: list[str] = []
    voice_target = ROOT / str(_get(cfg, "voice.samples_file", "positioning/voice-samples.md"))
    voice_example = ROOT / "positioning" / "voice-samples.example.md"
    if voice_target.exists():
        pass
    elif voice_example.exists():
        voice_target.parent.mkdir(parents=True, exist_ok=True)
        voice_target.write_text(voice_example.read_text())
        written.append(voice_target)
    else:
        notes.append(f"no {voice_example.name} to copy; create "
                     f"{_rel(voice_target)} by hand before the first draft")

    if not args.skip_claude_md:
        CLAUDE_MD.write_text(render_claude_md(cfg))
        written.append(CLAUDE_MD)

    print(f"Configured workspace for {company}\n")
    for p in written:
        print(f"  wrote  {_rel(p)}")
    for n in notes:
        print(f"  note   {n}")

    print("\nNext:")
    print("  1. uv run --with pyyaml skills/agent-onboarding/scripts/validate_config.py "
          "config/outbound.yaml")
